import pandas as pd

from src.database import engine


def load_sales_data():
    """Load sales records from the SQLite database."""
    query = "SELECT * FROM sales"

    with engine.connect() as connection:
        dataframe = pd.read_sql(query, connection)

    return dataframe


def calculate_kpis(dataframe):
    """Calculate key business performance indicators."""

    return {
        "total_revenue": dataframe["total_amount"].sum(),
        "total_sales": len(dataframe),
        "total_quantity": dataframe["quantity"].sum(),
        "average_sales": dataframe["total_amount"].mean()
    }


def category_performance(dataframe):
    """Calculate revenue generated by each category."""

    return (
        dataframe.groupby("category")["total_amount"]
        .sum()
        .sort_values(ascending=False)
    )


def top_products(dataframe):
    """Identify products generating the highest revenue."""

    return (
        dataframe.groupby("product_name")["total_amount"]
        .sum()
        .sort_values(ascending=False)
    )


def monthly_sales(dataframe):
    """Calculate monthly revenue trends."""

    dataframe = dataframe.copy()

    dataframe["sale_date"] = pd.to_datetime(
        dataframe["sale_date"]
    )

    dataframe["month"] = (
        dataframe["sale_date"].dt.to_period("M").astype(str)
    )

    return (
        dataframe.groupby("month")["total_amount"]
        .sum()
        .sort_index()
    )


if __name__ == "__main__":

    sales_data = load_sales_data()

    print("\nSALES ANALYTICS REPORT")
    print("=" * 45)

    print("\nKEY PERFORMANCE INDICATORS")
    for name, value in calculate_kpis(sales_data).items():
        print(f"{name}: {value:,.2f}")

    print("\nCATEGORY PERFORMANCE")
    print(category_performance(sales_data))

    print("\nTOP PRODUCTS")
    print(top_products(sales_data).head(5))

    print("\nMONTHLY SALES")
    print(monthly_sales(sales_data))
